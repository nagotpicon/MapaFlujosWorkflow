import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on('console', (m) => console.log('console', m.type(), m.text()));
await page.goto('http://localhost:5173');
await page.getByTestId('new-project').click();
await page.locator('.react-flow__pane').dblclick({ position: { x: 400, y: 300 } });
await page.getByTestId('node-title-input').fill('X');
await page.getByTestId('node-title-input').press('Enter');
const n = page.locator('.react-flow__node:has([data-node-title="X"])');
await n.click({ position: { x: 20, y: 12 } });
console.log('controls', await n.locator('.react-flow__resize-control').count());
const h = n.locator('.react-flow__resize-control.bottom.right');
console.log('handle', await h.count(), JSON.stringify(await h.boundingBox()), JSON.stringify(await n.boundingBox()));
const hb = await h.boundingBox();
console.log('at point', await page.evaluate(([x, y]) => { const el = document.elementFromPoint(x, y); return el ? `${el.tagName}.${el.className}` : 'none'; }, [hb.x + hb.width / 2, hb.y + hb.height / 2]));
await page.mouse.move(hb.x + hb.width / 2, hb.y + hb.height / 2);
await page.mouse.down();
await page.mouse.move(hb.x + 60, hb.y + 30, { steps: 4 });
console.log('mid', JSON.stringify(await n.boundingBox()));
await page.mouse.move(hb.x + 120, hb.y + 60, { steps: 4 });
await page.mouse.up();
await page.waitForTimeout(300);
console.log('after', JSON.stringify(await n.boundingBox()));
await browser.close();
