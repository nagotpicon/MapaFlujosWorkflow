import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost:5173');
await page.getByTestId('open-demo').click();
await page.waitForTimeout(1500);
await page.getByTestId('toggle-bottom').click();
await page.getByTestId('frame-toggle').click();
await page.getByRole('radio', { name: 'Cuadrícula que computa' }).click();
await page.getByLabel('Apoyo y fricción').click();
await page.locator('input[placeholder="sin límite"]').fill('6');
await page.locator('input[placeholder="sin límite"]').press('Enter');
await page.keyboard.press('Escape');
await page.getByTestId('heat-toggle').click();
await page.waitForTimeout(1500);
await page.screenshot({ path: '/tmp/claude-0/shots/grid.png' });
await page.getByTestId('open-explorer').click();
await page.getByTestId('explorer-topic').fill('Clases de guitarra');
await page.getByTestId('explorer-start').click();
await page.waitForTimeout(800);
await page.getByTestId('create-flow').click();
await page.waitForTimeout(1200);
await page.screenshot({ path: '/tmp/claude-0/shots/proposal2.png' });
await page.getByTestId('insert-proposal').click();
await page.waitForTimeout(1500);
await page.screenshot({ path: '/tmp/claude-0/shots/inserted.png' });
await browser.close();
