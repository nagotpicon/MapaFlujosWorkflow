// Recorrido visual automatizado: capturas de las pantallas principales.
import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://localhost:5173';
const out = process.argv[3] ?? '/tmp/claude-0/shots';
const theme = process.argv[4] ?? 'light';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: theme });
const page = await ctx.newPage();
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(`console: ${m.text()}`); });
page.on('pageerror', (e) => errors.push(`pageerror: ${e.message}`));
const shot = async (name) => { await page.waitForTimeout(700); await page.screenshot({ path: `${out}/${theme}-${name}.png` }); };
await page.goto(base);
await page.getByTestId('open-demo').click();
await page.waitForTimeout(2000);
await page.keyboard.press('Escape');
await page.getByTestId('toggle-bottom').click();
await shot('flow');
await page.screenshot({ path: `${out}/${theme}-toolbar-zoom.png`, clip: { x: 0, y: 0, width: 420, height: 300 } });
for (const v of ['Mental', 'Energía', 'Sistema', 'Simulación']) { await page.getByRole('radio', { name: v }).click(); await shot(`view-${v}`); }
await page.getByRole('radio', { name: 'Flujo' }).click();
await page.locator('[data-node-title="Clasificación de llamadas"]').click();
await shot('inspector-node');
await page.getByTestId('heat-toggle').click();
await shot('heat');
await page.getByTestId('toggle-bottom').click();
await page.getByTestId('tab-diagnostics').click();
await shot('diagnostics');
await page.getByTestId('open-monitor').click();
await page.waitForTimeout(2500);
await shot('monitor');
await page.keyboard.press('Escape');
await page.getByTestId('open-verdict').click();
await page.waitForTimeout(2500);
await shot('verdict');
await page.keyboard.press('Escape');
await page.getByTestId('open-explorer').click();
await page.waitForTimeout(800);
await shot('explorer-start');
await page.getByTestId('explorer-topic').fill('Clases particulares de guitarra');
await page.getByTestId('explorer-strategy').fill('repartir flyers por mi zona');
await page.getByTestId('explorer-start').click();
await page.waitForTimeout(1500);
await page.getByTestId('explorer-answer').fill('Con cinco alumnos recurrentes podría estar satisfecho.');
await page.getByTestId('explorer-send').click();
await page.waitForTimeout(1500);
await shot('explorer-conversation');
await page.getByTestId('create-flow').click();
await page.waitForTimeout(1500);
await shot('explorer-proposal');
console.log(errors.slice(0, 20).join('\n') || 'sin errores de consola');
await browser.close();
